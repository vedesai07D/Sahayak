/** A piece of content available in one or more languages. */
export type Localized = { en: string; hi?: string; mr?: string };
export type LocalizedList = { en: string[]; hi?: string[]; mr?: string[] };

export function pick(value: Localized | string | undefined, lang: Lang): string {
  if (!value) return "";
  if (typeof value === "string") return value;
  return value[lang] ?? value.en ?? "";
}

export function pickList(value: LocalizedList | string[] | undefined, lang: Lang): string[] {
  if (!value) return [];
  if (Array.isArray(value)) return value;
  return value[lang] ?? value.en ?? [];
}

